from __future__ import annotations

import html
from pathlib import Path

from finops_scanner.models import AuditSummary


def render_markdown_report(summary: AuditSummary) -> str:
    findings = summary.sorted_findings()
    high_count = sum(1 for f in findings if f.severity == "HIGH")
    med_count = sum(1 for f in findings if f.severity == "MEDIUM")
    low_count = sum(1 for f in findings if f.severity == "LOW")

    lines = [
        "# AWS Cost & Security Hygiene — Executive Audit Report",
        "",
        f"- **AWS Account:** `{summary.account_id}`",
        f"- **Regions Scanned:** `{', '.join(summary.regions_scanned)}` (+ Global S3)",
        f"- **Generated:** `{summary.generated_at_utc}` (`{summary.mode}` mode)",
        f"- **Identified Monthly Savings:** **${summary.total_monthly_savings_usd:,.2f} / month**",
        f"- **Projected Annualized Savings:** **${summary.total_annual_savings_usd:,.2f} / year**",
        f"- **Findings Breakdown:** {len(findings)} total ({high_count} HIGH, {med_count} MEDIUM, {low_count} LOW)",
        "",
        "---",
        "",
        "## Prioritized Findings",
        "",
        "| Severity | Check | Category | Resource | Region | Est. Save / Mo | Est. Save / Yr |",
        "| :--- | :--- | :--- | :--- | :--- | ---: | ---: |",
    ]

    for f in findings:
        lines.append(
            f"| **{f.severity}** | `{f.check_id}` | {f.category} | `{f.resource_id}` | `{f.region}` | "
            f"${f.estimated_monthly_savings_usd:,.2f} | ${f.estimated_annual_savings_usd:,.2f} |"
        )

    lines.extend(["", "---", "", "## Actionable Remediation Runbook", ""])
    for idx, f in enumerate(findings, start=1):
        lines.extend(
            [
                f"### {idx}. [{f.severity}] {f.category} — `{f.resource_id}` (`{f.region}`)",
                f"- **Estimated Savings:** ${f.estimated_monthly_savings_usd:,.2f}/mo (${f.estimated_annual_savings_usd:,.2f}/yr)",
                f"- **Diagnosis:** {f.summary}",
                "- **Verify & Remediate (AWS CLI):**",
                "```bash",
                f.remediation_cli,
                "```",
                "",
            ]
        )

    lines.extend(
        [
            "---",
            "*Generated by [aws-finops-guardrails](https://github.com/rnadagoud/aws-finops-guardrails) — Metadata-only read scan (zero customer data or secret access).*",
            "",
        ]
    )
    return "\n".join(lines)


