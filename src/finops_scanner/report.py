def write_reports(summary: AuditSummary, output_dir: str | Path) -> tuple[Path, Path]:
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    md_path = out / "executive-audit-report.md"
    html_path = out / "executive-audit-report.html"
    md_path.write_text(render_markdown_report(summary), encoding="utf-8")
    html_path.write_text(render_html_report(summary), encoding="utf-8")
    return md_path, html_path
